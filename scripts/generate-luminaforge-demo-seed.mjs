import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_PATH = path.join(ROOT, "seed/luminaforge-demo-seed.json");
const OUTPUT_PATH = path.join(ROOT, "sql/luminaforge_demo_seed.sql");
const TRANSACTION_OUTPUT_PATH = path.join(
  ROOT,
  "sql/luminaforge_reinit_transactions.sql",
);

export function readManifest(manifestPath = MANIFEST_PATH) {
  return JSON.parse(fs.readFileSync(manifestPath, "utf8"));
}

function duplicateIds(rows) {
  const seen = new Set();
  return rows.filter(({ id }) => {
    if (seen.has(id)) return true;
    seen.add(id);
    return false;
  });
}

export function validateManifest(manifest) {
  const errors = [];
  const tables = [
    ["USERS", manifest.users],
    ["PORTFOLIO", manifest.portfolio],
    ["TRANSACTIONS", manifest.transactions],
    ["LUXURY_ITEMS", manifest.luxuryItems],
  ];

  if (manifest.sourceAnchor !== "2026-06-01T00:00:00.000Z") {
    errors.push("sourceAnchor must be 2026-06-01T00:00:00.000Z");
  }
  if (manifest.targetSchema !== "LUMINAFORGE") {
    errors.push("targetSchema must be LUMINAFORGE");
  }

  for (const [name, rows] of tables) {
    if (!Array.isArray(rows)) {
      errors.push(`${name} must be an array`);
      continue;
    }
    if (duplicateIds(rows).length > 0) errors.push(`${name} contains duplicate IDs`);
    if (manifest.expectedCounts?.[name] !== rows.length) {
      errors.push(`${name} expected count does not match manifest rows`);
    }
  }

  const userIds = new Set((manifest.users ?? []).map(({ id }) => id));
  for (const row of [...(manifest.portfolio ?? []), ...(manifest.transactions ?? [])]) {
    if (!userIds.has(row.userId)) errors.push(`broken user reference ${row.userId}`);
  }
  if (manifest.users?.find(({ username }) => username === "demo_user")?.id !== 1) {
    errors.push("demo_user must retain ID 1");
  }

  const declaredTemporal = new Set(
    Object.entries(manifest.temporalColumns ?? {}).flatMap(([table, columns]) =>
      columns.map((column) => `${table}.${column}`),
    ),
  );
  const actualTemporal = new Set();
  for (const row of manifest.transactions ?? []) {
    if (!row.temporal) errors.push(`transaction ${row.id} lacks temporal metadata`);
    else actualTemporal.add("TRANSACTIONS.TIMESTAMP");
  }
  for (const key of actualTemporal) {
    if (!declaredTemporal.has(key)) errors.push(`undeclared temporal column ${key}`);
  }
  for (const key of declaredTemporal) {
    if (!actualTemporal.has(key)) errors.push(`declared temporal column has no metadata ${key}`);
  }

  if (errors.length > 0) throw new Error(errors.join("; "));
  return manifest;
}

function q(value) {
  if (value == null) return "NULL";
  if (typeof value === "number") return Number.isInteger(value) ? String(value) : String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

function insert(table, columns, values) {
  return `  INSERT INTO luminaforge.${table} (${columns.join(", ")}) VALUES (${values.join(", ")});`;
}

export function renderSeedSql(input) {
  const manifest = validateManifest(structuredClone(input));
  const inserts = [];
  for (const row of manifest.users) {
    inserts.push(insert("users", ["id", "username", "password", "role"], [row.id, q(row.username), q(row.password), q(row.role)]));
  }
  for (const row of manifest.luxuryItems) {
    inserts.push(insert("luxury_items", ["id", "name", "price", "category"], [row.id, q(row.name), row.price, q(row.category)]));
  }
  for (const row of manifest.portfolio) {
    inserts.push(insert("portfolio", ["id", "user_id", "symbol", "quantity", "avg_price"], [row.id, row.userId, q(row.symbol), row.quantity, row.avgPrice]));
  }
  for (const row of manifest.transactions) {
    const t = row.temporal;
    inserts.push(
      insert(
        "transactions",
        ["id", "user_id", "type", "amount", "asset", "timestamp"],
        [
          row.id,
          row.userId,
          q(row.type),
          row.amount,
          q(row.asset),
          `luminaforge.aegis_demo_seed.rebase_timestamp(l_anchor, ${t.months}, ${t.days}, ${t.milliseconds}, ${t.lastDayOfMonth ? 1 : 0})`,
        ],
      ),
    );
  }

  return `-- GENERATED by scripts/generate-luminaforge-demo-seed.mjs. DO NOT EDIT.
-- Source: seed/luminaforge-demo-seed.json
CREATE OR REPLACE PACKAGE luminaforge.aegis_demo_seed
AUTHID DEFINER
AS
  c_source_anchor CONSTANT VARCHAR2(24) := '${manifest.sourceAnchor}';
  FUNCTION rebase_timestamp(
    p_target_anchor IN TIMESTAMP WITH TIME ZONE,
    p_months IN PLS_INTEGER,
    p_days IN NUMBER,
    p_milliseconds IN NUMBER,
    p_last_day_of_month IN NUMBER
  ) RETURN TIMESTAMP;
  PROCEDURE initialize(
    p_target_anchor IN TIMESTAMP WITH TIME ZONE,
    p_users OUT NUMBER,
    p_portfolio OUT NUMBER,
    p_transactions OUT NUMBER,
    p_luxury_items OUT NUMBER
  );
END aegis_demo_seed;
/

CREATE OR REPLACE PACKAGE BODY luminaforge.aegis_demo_seed
AS
  FUNCTION rebase_timestamp(
    p_target_anchor IN TIMESTAMP WITH TIME ZONE,
    p_months IN PLS_INTEGER,
    p_days IN NUMBER,
    p_milliseconds IN NUMBER,
    p_last_day_of_month IN NUMBER
  ) RETURN TIMESTAMP
  IS
    l_anchor TIMESTAMP := CAST(SYS_EXTRACT_UTC(p_target_anchor) AS TIMESTAMP);
    l_midnight TIMESTAMP;
    l_clock INTERVAL DAY TO SECOND;
    l_month_date DATE;
    l_result TIMESTAMP;
  BEGIN
    IF p_target_anchor IS NULL THEN RETURN NULL; END IF;
    l_midnight := CAST(TRUNC(CAST(l_anchor AS DATE)) AS TIMESTAMP);
    l_clock := l_anchor - l_midnight;
    l_month_date := ADD_MONTHS(TRUNC(CAST(l_anchor AS DATE)), p_months);
    IF p_last_day_of_month = 1 THEN
      l_month_date := LAST_DAY(l_month_date);
    END IF;
    l_result := CAST(l_month_date AS TIMESTAMP) + l_clock;
    RETURN l_result
      + NUMTODSINTERVAL(p_days, 'DAY')
      + NUMTODSINTERVAL(p_milliseconds / 1000, 'SECOND');
  END rebase_timestamp;

  PROCEDURE initialize(
    p_target_anchor IN TIMESTAMP WITH TIME ZONE,
    p_users OUT NUMBER,
    p_portfolio OUT NUMBER,
    p_transactions OUT NUMBER,
    p_luxury_items OUT NUMBER
  )
  IS
    l_anchor TIMESTAMP WITH TIME ZONE :=
      COALESCE(p_target_anchor, SYSTIMESTAMP AT TIME ZONE 'UTC');
    l_broken_refs NUMBER;
    l_demo_user NUMBER;
  BEGIN
    DELETE FROM luminaforge.transactions;
    DELETE FROM luminaforge.portfolio;
    DELETE FROM luminaforge.luxury_items;
    DELETE FROM luminaforge.users;

${inserts.join("\n")}

    SELECT COUNT(*) INTO p_users FROM luminaforge.users;
    SELECT COUNT(*) INTO p_portfolio FROM luminaforge.portfolio;
    SELECT COUNT(*) INTO p_transactions FROM luminaforge.transactions;
    SELECT COUNT(*) INTO p_luxury_items FROM luminaforge.luxury_items;

    IF p_users != ${manifest.expectedCounts.USERS}
       OR p_portfolio != ${manifest.expectedCounts.PORTFOLIO}
       OR p_transactions != ${manifest.expectedCounts.TRANSACTIONS}
       OR p_luxury_items != ${manifest.expectedCounts.LUXURY_ITEMS} THEN
      RAISE_APPLICATION_ERROR(-20061, 'Demo seed row-count validation failed');
    END IF;

    SELECT COUNT(*) INTO l_broken_refs
    FROM (
      SELECT user_id FROM luminaforge.portfolio
      UNION ALL
      SELECT user_id FROM luminaforge.transactions
    ) child
    WHERE NOT EXISTS (
      SELECT 1 FROM luminaforge.users parent WHERE parent.id = child.user_id
    );
    IF l_broken_refs != 0 THEN
      RAISE_APPLICATION_ERROR(-20062, 'Demo seed referential validation failed');
    END IF;
    SELECT COUNT(*) INTO l_demo_user
    FROM luminaforge.users
    WHERE id = 1 AND username = 'demo_user';
    IF l_demo_user != 1 THEN
      RAISE_APPLICATION_ERROR(-20063, 'Demo seed identity validation failed');
    END IF;
    -- Caller owns COMMIT/ROLLBACK so the complete reset stays atomic.
  END initialize;
END aegis_demo_seed;
/
`;
}

export function renderTransactionResetSql(input) {
  const manifest = validateManifest(structuredClone(input));
  const inserts = manifest.transactions.map((row) => {
    const t = row.temporal;
    return insert(
      "transactions",
      ["id", "user_id", "type", "amount", "asset", "timestamp"],
      [
        row.id,
        row.userId,
        q(row.type),
        row.amount,
        q(row.asset),
        `luminaforge.aegis_demo_seed.rebase_timestamp(l_anchor, ${t.months}, ${t.days}, ${t.milliseconds}, ${t.lastDayOfMonth ? 1 : 0})`,
      ],
    );
  });
  return `-- GENERATED by scripts/generate-luminaforge-demo-seed.mjs. DO NOT EDIT.
-- Transaction-only reset used by the existing Break-Glass control.
CREATE OR REPLACE PROCEDURE luminaforge.aegis_demo_reinit_transactions
AUTHID DEFINER
AS
  l_anchor TIMESTAMP WITH TIME ZONE := SYSTIMESTAMP AT TIME ZONE 'UTC';
  l_count NUMBER;
BEGIN
  DELETE FROM luminaforge.transactions;
${inserts.join("\n")}
  SELECT COUNT(*) INTO l_count FROM luminaforge.transactions;
  IF l_count != ${manifest.expectedCounts.TRANSACTIONS} THEN
    RAISE_APPLICATION_ERROR(-20067, 'Transaction seed row-count validation failed');
  END IF;
  COMMIT;
END aegis_demo_reinit_transactions;
/
`;
}

export function generate() {
  const manifest = readManifest();
  const sql = renderSeedSql(manifest);
  fs.writeFileSync(OUTPUT_PATH, sql);
  fs.writeFileSync(TRANSACTION_OUTPUT_PATH, renderTransactionResetSql(manifest));
  return [OUTPUT_PATH, TRANSACTION_OUTPUT_PATH];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const outputPath of generate()) {
    console.log(`Generated ${path.relative(ROOT, outputPath)}`);
  }
}
